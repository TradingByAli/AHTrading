const DEFAULT_LANG = 'en';

function applyLang(lang) {
  const dict = I18N[lang] || I18N[DEFAULT_LANG];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll('.lang-btn').forEach(function (b) {
    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
  });
  localStorage.setItem('aht_lang', lang);
}

function initTheme() {
  const btn = document.getElementById('themeBtn');
  const icon = document.getElementById('themeIcon');
  const vd = document.getElementById('bgVideo');
  const vl = document.getElementById('bgVideoLight');
  function set(mode) {
    document.documentElement.dataset.theme = mode;
    localStorage.setItem('aht_theme', mode);
    if (icon) {
      if (mode === 'light') {
        icon.innerHTML = '<path d="M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8Z"/>';
      } else {
        icon.innerHTML = '<circle cx="12" cy="12" r="4"/><path d="M12 2v2M12 20v2M4.9 4.9l1.4 1.4M17.7 17.7l1.4 1.4M2 12h2M20 12h2M4.9 19.1l1.4-1.4M17.7 6.3l1.4-1.4"/>';
      }
    }
    if (mode === 'light') {
      if (vd) vd.pause();
      if (vl) { try { vl.play(); } catch (e) {} }
    } else {
      if (vl) vl.pause();
      if (vd) { try { vd.play(); } catch (e) {} }
    }
    if (typeof mountChart === 'function') mountChart();
  }
  if (btn) {
    btn.addEventListener('click', function () {
      const next = document.documentElement.dataset.theme === 'light' ? 'dark' : 'light';
      set(next);
    });
  }
  set(localStorage.getItem('aht_theme') === 'light' ? 'light' : 'dark');
}

var chartInterval = '60';

function chartConfig() {
  const theme = document.documentElement.dataset.theme === 'light' ? 'light' : 'dark';
  return {
    autosize: true,
    symbol: 'OANDA:XAUUSD',
    interval: chartInterval,
    timezone: 'Etc/UTC',
    theme: theme,
    style: '1',
    locale: 'en',
    backgroundColor: theme === 'light' ? 'rgba(255, 255, 255, 0.9)' : 'rgba(1, 5, 18, 0.9)',
    gridColor: theme === 'light' ? 'rgba(58, 70, 87, 0.18)' : 'rgba(58, 70, 87, 0.25)',
    allow_symbol_change: false,
    calendar: false,
    hide_side_toolbar: true,
    hide_top_toolbar: true,
    withdateranges: false,
    container_id: 'tradingview_chart',
    support_host: 'https://www.tradingview.com'
  };
}

function mountChart(retries) {
  const box = document.getElementById('tradingview_chart');
  if (!box) return;
  box.innerHTML = '';
  const s = document.createElement('script');
  s.type = 'text/javascript';
  s.src = 'https://s3.tradingview.com/external-embedding/embed-widget-advanced-chart.js';
  s.async = true;
  s.onerror = function () {
    if ((retries || 0) < 2) {
      setTimeout(function () { mountChart((retries || 0) + 1); }, 2500);
    }
  };
  s.textContent = JSON.stringify(chartConfig());
  box.appendChild(s);
}

function initChartTabs() {
  const btns = document.querySelectorAll('.chart-tab');
  btns.forEach(function (b) {
    b.addEventListener('click', function () {
      btns.forEach(function (x) { x.classList.remove('active'); });
      b.classList.add('active');
      chartInterval = b.getAttribute('data-interval');
      mountChart();
    });
  });
}

function initSteps() {
  var grid = document.getElementById('stepsGrid');
  var toggle = document.getElementById('stepsToggle');
  if (grid && toggle) {
    toggle.addEventListener('click', function () {
      var open = grid.classList.toggle('collapsed');
      toggle.setAttribute('aria-expanded', open ? 'false' : 'true');
      var label = open ? 'stepsShow' : 'stepsHide';
      var el = toggle.querySelector('.steps-label');
      if (el && I18N[DEFAULT_LANG]) {
        var lang = localStorage.getItem('aht_lang') || 'en';
        el.textContent = I18N[I18N[lang] ? lang : 'en'][label];
      }
    });
  }
  var thumbs = document.querySelectorAll('.step');
  var lb = document.getElementById('lightbox');
  var lbImg = document.querySelector('.lb-img');
  var dotsEl = document.getElementById('lbDots');
  var idx = 0;
  var srcs = [];
  var dots = [];
  for (var i = 0; i < thumbs.length; i++) {
    srcs.push(thumbs[i].querySelector('img').src);
    var d = document.createElement('span');
    d.className = 'lb-dot';
    dotsEl.appendChild(d);
    dots.push(d);
  }
  function show(n) {
    idx = (n + srcs.length) % srcs.length;
    lbImg.src = srcs[idx];
    dots.forEach(function (d, i) { d.classList.toggle('on', i === idx); });
  }
  thumbs.forEach(function (t, i) {
    t.addEventListener('click', function () { show(i); lb.hidden = false; });
  });
  document.querySelector('.lb-close').addEventListener('click', function () { lb.hidden = true; });
  document.querySelector('.lb-prev').addEventListener('click', function () { show(idx - 1); });
  document.querySelector('.lb-next').addEventListener('click', function () { show(idx + 1); });
  lb.addEventListener('click', function (e) { if (e.target === lb) lb.hidden = true; });
  dots.forEach(function (d, i) {
    d.addEventListener('click', function () { show(i); });
  });
  document.addEventListener('keydown', function (e) {
    if (lb.hidden) return;
    if (e.key === 'Escape') lb.hidden = true;
    if (e.key === 'ArrowLeft') show(idx - 1);
    if (e.key === 'ArrowRight') show(idx + 1);
  });
}

function initNewsFrame() {
  const frame = document.querySelector('.news-box iframe');
  if (!frame) return;
  let loaded = false;
  frame.addEventListener('load', function () { loaded = true; });
  setTimeout(function () {
    if (!loaded) {
      frame.src = frame.src.replace('sslecal2.investing.com', 'sslecal2.forexprostools.com');
    }
  }, 8000);
}

function initNav() {
  const burger = document.getElementById('burger');
  const links = document.getElementById('navLinks');
  burger.addEventListener('click', function () {
    const open = links.classList.toggle('open');
    burger.setAttribute('aria-expanded', open ? 'true' : 'false');
  });
  links.querySelectorAll('a').forEach(function (a) {
    a.addEventListener('click', function () {
      links.classList.remove('open');
      burger.setAttribute('aria-expanded', 'false');
    });
  });

  const sections = Array.prototype.slice.call(document.querySelectorAll('section[id]'));
  const anchors = Array.prototype.slice.call(links.querySelectorAll('a[href^="#"]'));
  function active() {
    const probe = window.scrollY + window.innerHeight * 0.35;
    let current = sections.length ? sections[0].id : '';
    sections.forEach(function (s) { if (s.offsetTop <= probe) current = s.id; });
    anchors.forEach(function (a) {
      a.classList.toggle('active', a.getAttribute('href') === '#' + current);
    });
  }
  window.addEventListener('scroll', active, { passive: true });
  active();
}

function initReveal() {
  const io = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) {
        entry.target.classList.add('in');
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });
  document.querySelectorAll('.reveal').forEach(function (el) { io.observe(el); });
}

document.addEventListener('DOMContentLoaded', function () {
  const saved = localStorage.getItem('aht_lang');
  applyLang(I18N[saved] ? saved : DEFAULT_LANG);
  document.querySelectorAll('.lang-btn').forEach(function (b) {
    b.addEventListener('click', function () { applyLang(b.getAttribute('data-lang')); });
  });
  initNav();
  initReveal();
  initChartTabs();
  initSteps();
  initNewsFrame();
  initTheme();
});
